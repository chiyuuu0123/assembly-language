; Exercise PRINT_CELL for all 45 inputs, checking registers and SP.
.MODEL SMALL
.STACK 100H
.DATA
SAVEBX DW ?
SAVESI DW ?
SAVESP DW ?
PASSMSG DB 'Register and stack checks passed (45 cells).',0DH,0AH,'$'
FAILMSG DB 'FAIL: register or stack mismatch.',0DH,0AH,'$'
.CODE
START:
    MOV AX,@DATA
    MOV DS,AX
    MOV BX,9
TEST_ROW:
    MOV SI,1
TEST_CELL:
    MOV SAVEBX,BX
    MOV SAVESI,SI
    MOV SAVESP,SP
    MOV AX,1234H
    MOV CX,0A55H
    MOV DX,5678H
    MOV BP,1357H
    MOV DI,2468H
    CALL PRINT_CELL
    CMP AX,1234H
    JNE BAD_STATE
    CMP BX,SAVEBX
    JNE BAD_STATE
    CMP CX,0A55H
    JNE BAD_STATE
    CMP DX,5678H
    JNE BAD_STATE
    CMP SI,SAVESI
    JNE BAD_STATE
    CMP BP,1357H
    JNE BAD_STATE
    CMP DI,2468H
    JNE BAD_STATE
    CMP SP,SAVESP
    JNE BAD_STATE
    INC SI
    CMP SI,BX
    JBE TEST_CELL
    CALL NEWLINE
    DEC BX
    JNZ TEST_ROW
    LEA DX,PASSMSG
    MOV AH,09H
    INT 21H
    MOV AX,4C00H
    INT 21H
BAD_STATE:
    LEA DX,FAILMSG
    MOV AH,09H
    INT 21H
    MOV AX,4C01H
    INT 21H
INCLUDE CELL.INC
INCLUDE PRINT.INC
END START
