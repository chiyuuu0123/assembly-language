.MODEL SMALL
.STACK 800H
.DATA
PROMPT DB 'Enter n (1-100): $'
BADMSG DB 'Invalid input. Enter an integer from 1 to 100.',0DH,0AH,'$'
RESULT DB 'Result: $'
STACKMSG DB 'Recursion stack bytes: $'
INBUF DB 8,0,8 DUP(0)
DECWORK DW 5 DUP(0)
PEAK DW 0
INCLUDE FIBDATA.INC
.CODE
START:
    MOV AX,@DATA
    MOV DS,AX
READ_AGAIN:
    LEA DX,PROMPT
    MOV AH,09H
    INT 21H
    MOV BYTE PTR [INBUF+1],0
    LEA DX,INBUF
    MOV AH,0AH
    INT 21H
    CALL NEWLINE
    XOR CX,CX
    MOV CL,[INBUF+1]
    JCXZ BAD_INPUT
    CMP CX,3
    JA BAD_INPUT
    LEA SI,INBUF+2
    XOR AX,AX
    MOV BX,10
PARSE_DIGIT:
    MOV DL,[SI]
    CMP DL,'0'
    JB BAD_INPUT
    CMP DL,'9'
    JA BAD_INPUT
    SUB DL,'0'
    XOR DH,DH
    PUSH DX
    MUL BX
    POP DX
    ADD AX,DX
    INC SI
    LOOP PARSE_DIGIT
    CMP AX,1
    JB BAD_INPUT
    CMP AX,100
    JA BAD_INPUT
    JMP RUN_FIB
BAD_INPUT:
    LEA DX,BADMSG
    MOV AH,09H
    INT 21H
    JMP READ_AGAIN
RUN_FIB:
    MOV BX,AX
    MOV DI,SP
    CALL FIB
    MOV AX,SP
    SUB AX,DI
    MOV PEAK,AX
    MOV AX,BX
    MOV CX,10
    MUL CX
    MOV SI,AX
    XOR DI,DI
    MOV CX,5
COPY_WORD:
    MOV AX,FIBVALS[SI]
    MOV DECWORK[DI],AX
    ADD SI,2
    ADD DI,2
    LOOP COPY_WORD
    LEA DX,RESULT
    MOV AH,09H
    INT 21H
    CALL PRINT_DEC
    CALL NEWLINE
    LEA DX,STACKMSG
    MOV AH,09H
    INT 21H
    MOV AX,PEAK
    CALL PRINT_U16
    CALL NEWLINE
    MOV AX,4C00H
    INT 21H

; Divide the work copy by 10 from most to least significant word.
PRINT_DEC PROC NEAR
    XOR CX,CX
    MOV BX,10
DEC_DIGIT:
    XOR DX,DX
    XOR DI,DI
    MOV SI,8
DEC_WORD:
    MOV AX,DECWORK[SI]
    DIV BX
    MOV DECWORK[SI],AX
    OR DI,AX
    SUB SI,2
    JNS DEC_WORD
    PUSH DX
    INC CX
    OR DI,DI
    JNZ DEC_DIGIT
SHOW_DIGIT:
    POP DX
    ADD DL,'0'
    MOV AH,02H
    INT 21H
    LOOP SHOW_DIGIT
    RET
PRINT_DEC ENDP
INCLUDE PRINT.INC
INCLUDE FIBCORE.INC
END START
